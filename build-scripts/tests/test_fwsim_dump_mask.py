#!/usr/bin/env python3
"""Rule Status fixture (`reaper_fwsim --dump-inputs`): no WAN address leaves the router in it (2026-11-08).

WHY. The fixture is what a field tester sends in, and it said "the WAN addresses are masked as [WAN-IP]". But
topology.txt printed every router address in clear, the addr file kept the WAN broadcast (`brd`, which gives the
WAN /24 away), and only the first address of the primary WAN interface was masked - a second WAN unit's address
travelled as is. Seen on the owner's own dump.

WHAT IT DOES.
- Builds the ROUTER build of the walker on the build host (the dump code is not in the host build), with nvram and
  _eval stubbed, and runs the real `--run --dump-inputs DIR` against fake ip / iptables-save / ip6tables-save /
  ipset commands describing a dual-WAN router (WAN v4 + v6 on wan0, a /30 on wan1).
- Checks: no WAN address (either unit, v4 or v6) and no WAN broadcast appears in any fixture file; the tokens
  [WAN-IP] / [WAN-BRD] are where they were; a WAN address with a port is masked; look-alike addresses that only
  START or END like a WAN address (198.51.100.64, 2001:db8:aa::451, 2001:db8:aa::45:1, 1203.0.113.45) are left
  alone; the LAN addresses are kept; the topology header says what is masked.
"""
import os, re, shutil, stat, subprocess, sys, tempfile

SRC = sys.argv[1] if len(sys.argv) > 1 else os.environ.get("REAPER_ROUTER_SRC", "")
walker = os.path.join(SRC, "reaper_fwsim", "reaper_fwsim.c") if SRC else ""
if not walker or not os.path.isfile(walker):
    print("SKIP: no router source tree (argv[1] / REAPER_ROUTER_SRC)"); sys.exit(77)
CC = shutil.which("gcc") or shutil.which("cc")
if not CC or not shutil.which("sh"):
    print("SKIP: no host C compiler / sh"); sys.exit(77)
fails = []
def check(name, cond, detail=""):
    print(("ok   " if cond else "FAIL ") + name)
    if not cond: fails.append(name + (" - " + str(detail)[:500] if detail else ""))

W0, W0BRD, W1, W1BRD, W6 = "203.0.113.45", "203.0.113.255", "198.51.100.6", "198.51.100.7", "2001:db8:aa::45"
LAN4, LAN6 = "192.168.50.1", "2001:db8:bb::1"
DECOYS = ["198.51.100.64", "2001:db8:aa::451", "2001:db8:aa::45:1", "1203.0.113.45"]

STUBS = r'''
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>
#include <fcntl.h>
#include <sys/wait.h>
char *nvram_get(const char *k)
{
	static char v[64][256]; static int n; char line[600]; FILE *f = fopen(getenv("NVFILE"), "r"); size_t kl = strlen(k);
	if (!f) return NULL;
	while (fgets(line, sizeof(line), f)) {
		if (!strncmp(line, k, kl) && line[kl] == '=') {
			char *s = v[n++ % 64]; snprintf(s, 256, "%s", line + kl + 1); s[strcspn(s, "\n")] = 0; fclose(f); return s;
		}
	}
	fclose(f); return NULL;
}
int _eval(char *const argv[], const char *path, int timeout, int *ppid)
{
	int st; pid_t p = fork(); (void)timeout; (void)ppid;
	if (p == 0) {
		if (path) { int fd = open(path[0] == '>' ? path + 1 : path, O_WRONLY | O_CREAT | O_TRUNC, 0644); if (fd >= 0) { dup2(fd, 1); dup2(fd, 2); } }
		execvp(argv[0], argv); _exit(127);
	}
	if (p < 0 || waitpid(p, &st, 0) < 0) return -1;
	return WIFEXITED(st) ? WEXITSTATUS(st) : -1;
}
char *reaper_fw_list_get(char *k) { (void)k; return strdup(""); }
char *reaper_pbr_rl_get(void) { return strdup(""); }
char *rw_list_get(const char *k) { (void)k; return strdup(""); }
'''

IP = r'''#!/bin/sh
case "$*" in
  "-o -4 addr"*|"-4 -o addr"*) cat "$FX/addr4";;
  "-o -6 addr"*|"-6 -o addr"*) cat "$FX/addr6";;
  "-o addr"*) cat "$FX/addr4" "$FX/addr6";;
  "-4 rule"*) printf '0:\tfrom all lookup local\n100:\tfrom %s lookup 101\n32766:\tfrom all lookup main\n' "$W1";;
  "-6 rule"*) printf '0:\tfrom all lookup local\n32766:\tfrom all lookup main\n';;
  *) exit 0;;
esac
'''
ADDR4 = ("1: lo    inet 127.0.0.1/8 scope host lo\\       valid_lft forever preferred_lft forever\n"
         "5: eth0    inet %s/24 brd %s scope global eth0\\       valid_lft forever preferred_lft forever\n"
         "6: eth1    inet %s/30 brd %s scope global eth1\\       valid_lft forever preferred_lft forever\n"
         "9: br0    inet %s/24 brd 192.168.50.255 scope global br0\\       valid_lft forever preferred_lft forever\n") % (W0, W0BRD, W1, W1BRD, LAN4)
ADDR6 = ("5: eth0    inet6 %s/64 scope global dynamic \\       valid_lft 86000sec preferred_lft 86000sec\n"
         "5: eth0    inet6 fe80::1/64 scope link \\       valid_lft forever preferred_lft forever\n"
         "9: br0    inet6 %s/64 scope global \\       valid_lft forever preferred_lft forever\n") % (W6, LAN6)
SAVE4 = """# Generated by iptables-save (synthetic - test_fwsim_dump_mask.py)
*nat
:PREROUTING ACCEPT [0:0]
:POSTROUTING ACCEPT [0:0]
-A PREROUTING -d %(w0)s/32 -p tcp -m tcp --dport 443 -j DNAT --to-destination %(w0)s:443
-A PREROUTING -d %(w1)s/32 -j VSERVER
-A POSTROUTING -o eth1 -j SNAT --to-source %(w1)s
-A POSTROUTING -s 198.51.100.64/26 -j ACCEPT
-A POSTROUTING -s 1203.0.113.45 -j ACCEPT
COMMIT
*filter
:INPUT ACCEPT [0:0]
:FORWARD DROP [0:0]
:OUTPUT ACCEPT [0:0]
-A INPUT -d %(w0b)s/32 -j DROP
-A INPUT -d %(w1b)s/32 -j DROP
-A INPUT -i br0 -d %(lan4)s -j ACCEPT
-A FORWARD -i br0 -o eth0 -j ACCEPT
COMMIT
""" % {"w0": W0, "w1": W1, "w0b": W0BRD, "w1b": W1BRD, "lan4": LAN4}
SAVE6 = """# Generated by ip6tables-save (synthetic)
*filter
:INPUT ACCEPT [0:0]
:FORWARD DROP [0:0]
:OUTPUT ACCEPT [0:0]
-A INPUT -d %(w6)s/128 -p udp -m udp --dport 51820 -j ACCEPT
-A INPUT -d 2001:db8:aa::451/128 -j ACCEPT
-A INPUT -d 2001:db8:aa::45:1/128 -j ACCEPT
-A FORWARD -i br0 -s %(lan6)s/64 -j ACCEPT
COMMIT
""" % {"w6": W6, "lan6": LAN6}
NV = "\n".join([
    "lan_ifname=br0", "lan_ipaddr=" + LAN4, "wan0_ifname=eth0", "wan0_proto=dhcp", "wan0_ipaddr=" + W0,
    "wan1_ifname=eth1", "wan1_proto=static", "wan1_ipaddr=" + W1, "wan1_primary=0", "productid=RT-TEST",
    "buildno=102.10", "vts_enable_x=1", "vts_rulelist=<web>443>TCP>192.168.50.20>443>" + W0, "fw_enable_x=1", ""])

def tool(path, body):
    open(path, "w", newline="\n").write(body); os.chmod(path, 0o755)

with tempfile.TemporaryDirectory() as td:
    inc, fx, binp = os.path.join(td, "inc"), os.path.join(td, "fx"), os.path.join(td, "bin")
    for d in (inc, fx, binp): os.makedirs(d)
    open(os.path.join(inc, "bcmnvram.h"), "w").write('char *nvram_get(const char *k);\n#define nvram_safe_get(k) (nvram_get(k) ? nvram_get(k) : "")\n')
    open(os.path.join(inc, "shutils.h"), "w").write("int _eval(char *const argv[], const char *path, int timeout, int *ppid);\n")
    open(os.path.join(inc, "shared.h"), "w").write("char *reaper_fw_list_get(char *k);\nchar *reaper_pbr_rl_get(void);\nchar *rw_list_get(const char *k);\n")
    open(os.path.join(td, "stubs.c"), "w").write(STUBS)
    exe = os.path.join(td, "fwsim_router")
    r = subprocess.run([CC, "-std=gnu99", "-Wall", "-Wextra", "-Wno-unused-parameter", "-Wno-sign-compare", "-Wno-unused-function",
                        "-I" + inc, "-o", exe, walker, os.path.join(td, "stubs.c")], capture_output=True, text=True)
    check("the router build of the walker compiles on the host (stubbed nvram / _eval)", r.returncode == 0, r.stderr[-800:])
    if r.returncode == 0:
        for name, body in (("addr4", ADDR4), ("addr6", ADDR6)): open(os.path.join(fx, name), "w").write(body)
        tool(os.path.join(binp, "ip"), IP)
        tool(os.path.join(binp, "iptables-save"), "#!/bin/sh\ncat <<'EOF'\n" + SAVE4 + "EOF\n")
        tool(os.path.join(binp, "ip6tables-save"), "#!/bin/sh\ncat <<'EOF'\n" + SAVE6 + "EOF\n")
        tool(os.path.join(binp, "ipset"), "#!/bin/sh\nprintf 'Name: reaper_wan\\nType: hash:ip\\nMembers:\\n%s\\n%s\\n' \"$W0\" \"$W1\"\n")
        nvf = os.path.join(td, "nv.txt"); open(nvf, "w").write(NV)
        env = dict(os.environ, PATH=binp + os.pathsep + os.environ.get("PATH", ""), FX=fx, NVFILE=nvf, W0=W0, W1=W1)
        dump = os.path.join(td, "dump")
        r = subprocess.run([exe, "--run", "--json", os.path.join(td, "out.json"), "--dump-inputs", dump],
                           capture_output=True, text=True, env=env, timeout=120)
        files = sorted(os.listdir(dump)) if os.path.isdir(dump) else []
        check("--dump-inputs wrote the fixture", "topology.txt" in files and "iptables-save" in files and "addr" in files,
              (r.returncode, files, r.stderr[-400:]))
        allt = {f: open(os.path.join(dump, f), encoding="utf-8", errors="replace").read() for f in files}
        blob = "\n".join(allt.values())

        def whole(addr, text):
            """addr as a whole address in text (the same boundaries the walker uses)"""
            v6 = ":" in addr
            pat = (r"(?<![0-9A-Fa-f:])" + re.escape(addr) + r"(?![0-9A-Fa-f]|:[0-9A-Fa-f:])") if v6 else \
                  (r"(?<![0-9.])" + re.escape(addr) + r"(?![0-9]|\.[0-9])")
            return [f for f, t in allt.items() if re.search(pat, t)] if text is None else re.search(pat, text) is not None
        for a, what in ((W0, "wan0 IPv4"), (W1, "wan1 IPv4 (second WAN unit)"), (W6, "wan0 IPv6"),
                        (W0BRD, "wan0 broadcast"), (W1BRD, "wan1 broadcast")):
            left = whole(a, None)
            check("no %s left in any fixture file" % what, not left, left)
        topo = allt.get("topology.txt", "")
        check("topology.txt: the WAN lines are masked, the LAN lines kept",
              re.search(r"^eth0 \[WAN-IP\]/24$", topo, re.M) and re.search(r"^eth1 \[WAN-IP\]/30$", topo, re.M)
              and re.search(r"^eth0 \[WAN-IP\]/64$", topo, re.M) and ("br0 %s/24" % LAN4) in topo and ("br0 %s/64" % LAN6) in topo, topo)
        check("topology.txt: the header says what is masked", "masked as [WAN-IP], its IPv4 broadcast as [WAN-BRD]" in topo, topo[:300])
        ad = allt.get("addr", "")
        check("addr: WAN address and broadcast tokens in place", "inet [WAN-IP]/24 brd [WAN-BRD]" in ad and "inet [WAN-IP]/30 brd [WAN-BRD]" in ad, ad)
        s4 = allt.get("iptables-save", "")
        check("iptables-save: a WAN address with a port is masked", "--to-destination [WAN-IP]:443" in s4, s4)
        check("iptables-save: the WAN broadcasts are masked", "-A INPUT -d [WAN-BRD]/32 -j DROP" in s4, s4)
        for d in DECOYS:
            check("look-alike %s is not touched" % d, d in blob, "")
        check("LAN addresses are kept", ("-d %s -j ACCEPT" % LAN4) in s4 and ("-s %s/64" % LAN6) in allt.get("ip6tables-save", ""), "")
        nvt = allt.get("nv", "")
        check("nv: wan0_ipaddr and a WAN address inside a rule list are masked; the second WAN's address is nowhere",
              "wan0_ipaddr=[WAN-IP]" in nvt and "vts_rulelist=<web>443>TCP>192.168.50.20>443>[WAN-IP]" in nvt and W1 not in nvt, nvt)
        check("iprule4 / ipsets: the second WAN's address is masked", "from [WAN-IP] lookup 101" in allt.get("iprule4", "")
              and W1 not in allt.get("ipsets.txt", "x" + W1), (allt.get("iprule4"), allt.get("ipsets.txt")))

print("%d checks failed" % len(fails) if fails else "all checks passed")
for f in fails: print("  " + f)
sys.exit(1 if fails else 0)
